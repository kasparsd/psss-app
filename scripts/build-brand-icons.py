#!/usr/bin/env python3
"""Builds the bundled brand icons.

Inputs (downloaded by hand, never committed):
  --simple-icons DIR   the unpacked `simple-icons` npm package (SVG files are CC0)
  --tranco FILE        the Tranco top-1m CSV, used only on this machine to pick which brands matter

Outputs:
  App/Assets.xcassets/Brands/<slug>.imageset   one vector SVG per brand, template rendering
  App/Core/BrandIcons.swift                    domain -> (slug, hex colour)

A domain maps to a brand when it is listed in OVERRIDES, its name (`paypal` in paypal.com) equals the icon's slug
or title, or it equals the host of the icon's source link. The most popular 1000 brands are kept.
"""
import argparse, csv, json, os, re, shutil
from urllib.parse import urlparse

LIMIT = 1000
OVERRIDES = {
    "google.com": "google", "youtube.com": "youtube", "youtu.be": "youtube", "apple.com": "apple",
    "icloud.com": "icloud", "ebay.com": "ebay", "microsoft.com": "microsoft", "live.com": "microsoft",
    "office.com": "microsoftoffice", "outlook.com": "microsoftoutlook", "amazon.com": "amazon",
    "x.com": "x", "twitter.com": "x", "fb.com": "facebook", "t.me": "telegram", "wa.me": "whatsapp",
    "linkedin.com": "linkedin", "github.com": "github", "githubusercontent.com": "github",
    "wikipedia.org": "wikipedia", "facebook.com": "facebook", "instagram.com": "instagram", "paypal.me": "paypal", "spotify.com": "spotify", "adobe.com": "adobe",
}
# Card networks are always bundled; App/Core/CardBrand.swift detects them from the card number.
CARD_NETWORKS = ["visa", "mastercard", "americanexpress", "discover", "jcb", "dinersclub"]
NOISE = {"github.com", "commons.wikimedia.org", "wikimedia.org", "en.wikipedia.org", "gitlab.com", "figma.com"}

def registrable(host):
    host = host.lower().removeprefix("www.")
    parts = host.split(".")
    if len(parts) >= 3 and parts[-2] in {"co", "com", "org", "net", "gov", "ac"} and len(parts[-1]) == 2:
        return ".".join(parts[-3:])
    return ".".join(parts[-2:])

def norm(text):
    return re.sub(r"[^a-z0-9]", "", text.lower())

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--simple-icons", required=True)
    ap.add_argument("--tranco", required=True)
    ap.add_argument("--root", default=os.path.join(os.path.dirname(__file__), ".."))
    args = ap.parse_args()

    data = json.load(open(os.path.join(args.simple_icons, "data/simple-icons.json")))
    by_slug = {i["slug"]: i for i in data}
    by_name = {}
    by_source = {}
    for i in data:
        by_name.setdefault(norm(i["title"]), i["slug"])
        by_name.setdefault(norm(i["slug"]), i["slug"])
        host = registrable(urlparse(i.get("source", "")).netloc)
        if host and host not in NOISE:
            by_source.setdefault(host, i["slug"])

    domains, slugs = {}, list(CARD_NETWORKS)
    with open(args.tranco) as f:
        for _, domain in csv.reader(f):
            slug = OVERRIDES.get(domain) or by_name.get(norm(domain.split(".")[0])) or by_source.get(domain)
            if slug not in by_slug:
                continue
            if slug not in slugs:
                if len(slugs) >= LIMIT:
                    continue
                slugs.append(slug)
            domains[domain] = slug
            if len(slugs) >= LIMIT and len(domains) > 4 * LIMIT:
                break

    root = os.path.abspath(args.root)
    brands = os.path.join(root, "App/Assets.xcassets/Brands")
    shutil.rmtree(os.path.join(root, "App/Assets.xcassets"), ignore_errors=True)
    os.makedirs(brands)
    json.dump({"info": {"author": "xcode", "version": 1}}, open(os.path.join(root, "App/Assets.xcassets/Contents.json"), "w"))
    json.dump({"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": False}},
              open(os.path.join(brands, "Contents.json"), "w"))
    for slug in slugs:
        d = os.path.join(brands, f"brand-{slug}.imageset")
        os.makedirs(d)
        shutil.copy(os.path.join(args.simple_icons, "icons", f"{slug}.svg"), os.path.join(d, f"{slug}.svg"))
        json.dump({"images": [{"filename": f"{slug}.svg", "idiom": "universal"}],
                   "info": {"author": "xcode", "version": 1},
                   "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"}},
                  open(os.path.join(d, "Contents.json"), "w"))

    lines = ["// Generated by scripts/build-brand-icons.py from Simple Icons (CC0). Do not edit.",
             "// Brand names and logos remain trademarks of their owners.", "",
             "enum BrandIcons {",
             "    /// Registrable domain -> (asset name, brand colour).",
             "    static let byDomain: [String: (asset: String, hex: UInt32)] = ["]
    for domain in sorted(domains):
        slug = domains[domain]
        lines.append(f'        "{domain}": ("brand-{slug}", 0x{by_slug[slug]["hex"]}),')
    lines += ["    ]", "}", ""]
    open(os.path.join(root, "App/Core/BrandIcons.swift"), "w").write("\n".join(lines))
    print(f"{len(slugs)} brands, {len(domains)} domains")

main()
