#!/usr/bin/env python3
"""Generates App/Core/PublicSuffixList.swift from the Public Suffix List.

Downloads https://publicsuffix.org/list/public_suffix_list.dat (plain GET, nothing else is sent) and writes the rules,
ICANN and PRIVATE sections both, as one Swift raw string literal. Internationalized rules are converted to punycode
so lookups work on the ASCII host form. Run it again to refresh the list; commit the regenerated file.

    python3 scripts/build-public-suffix.py [--source FILE]   (--source reads a local copy instead of downloading)
"""
import argparse, datetime, os, urllib.request

URL = "https://publicsuffix.org/list/public_suffix_list.dat"


def ascii_rule(rule):
    labels = []
    for label in rule.split("."):
        labels.append(label if label == "*" or label.isascii() else label.encode("idna").decode("ascii"))
    return ".".join(labels)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "App", "Core", "PublicSuffixList.swift"))
    args = ap.parse_args()
    if args.source:
        text = open(args.source, encoding="utf-8").read()
    else:
        with urllib.request.urlopen(URL, timeout=60) as r:
            text = r.read().decode("utf-8")
    rules = set()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        rule = line.split()[0].lower()
        exception = rule.startswith("!")
        rules.add(("!" if exception else "") + ascii_rule(rule.lstrip("!")))
    body = "\n".join(sorted(rules))
    assert '"""' not in body and "#" not in body
    date = datetime.date.today().isoformat()
    out = f'''// GENERATED by scripts/build-public-suffix.py. Do not edit by hand.
//
// Public Suffix List, https://publicsuffix.org/list/public_suffix_list.dat, fetched {date}.
// Contains the ICANN and PRIVATE sections. Rules are lowercase and internationalized rules are stored in punycode (xn--),
// so lookups work on the ASCII host form. One rule per line: `*.ck` is a wildcard rule, `!www.ck` is an exception rule.
//
// The Public Suffix List is licensed under the Mozilla Public License, v. 2.0. A copy of the MPL is at
// https://mozilla.org/MPL/2.0/. The list is maintained at https://publicsuffix.org/.

import Foundation

enum PublicSuffixList {{
    /// Parsed once on first use.
    static let rules: (normal: Set<String>, wildcard: Set<String>, exception: Set<String>) = {{
        var normal = Set<String>(), wildcard = Set<String>(), exception = Set<String>()
        for line in raw.split(separator: "\\n") {{
            if line.hasPrefix("!") {{ exception.insert(String(line.dropFirst())) }}
            else if line.hasPrefix("*.") {{ wildcard.insert(String(line.dropFirst(2))) }}
            else {{ normal.insert(String(line)) }}
        }}
        return (normal, wildcard, exception)
    }}()

    private static let raw = #"""
{body}
"""#
}}
'''
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"{len(rules)} rules -> {os.path.relpath(args.out)}")


if __name__ == "__main__":
    main()
