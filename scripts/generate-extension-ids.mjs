// Writes App/Core/Relay/ExtensionIDs.swift: the browser extensions the app's relay serves, compiled into the app so a changed
// text file next to the host cannot widen access (docs/browser-extension.md, "Host and app"). Node 24.
//
//   node scripts/generate-extension-ids.mjs          write the file
//   node scripts/generate-extension-ids.mjs --check  exit 1 when the file is out of date (test-relay.sh runs this)
//
// Sources: Extensions/Browser/extension-ids.json (store IDs; "development" is for debug builds only) and the Firefox add-on id
// in Extensions/Browser/targets/firefox.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ids = JSON.parse(readFileSync(join(root, 'Extensions/Browser/extension-ids.json'), 'utf8'));
const gecko = JSON.parse(readFileSync(join(root, 'Extensions/Browser/targets/firefox.json'), 'utf8')).browser_specific_settings.gecko.id;
const store = Object.values(ids.chromium).filter(Boolean);
const development = ids.development ? [ids.development] : [];
const list = (items) => items.map((i) => `"${i}"`).join(', ');
for (const id of [...store, ...development]) if (!/^[a-p]{32}$/.test(id)) throw new Error(`not a Chromium extension id: ${id}`);
if (!/^[\w.@-]+$/.test(gecko)) throw new Error(`not a plain add-on id: ${gecko}`);

const text = `// Generated by scripts/generate-extension-ids.mjs from Extensions/Browser/extension-ids.json and targets/firefox.json. Do not edit.

/// The browser extensions the relay serves. The host passes the one that started it as \`caller\`; anything else is refused.
enum ExtensionIDs {
    /// Chrome Web Store and Edge Add-ons ids (empty until the first upload).
    static let chromium: [String] = [${list(store)}]
    /// The development extension (\`build.py dev-key\`). Debug builds only: a release build does not know it.
    static let development: [String] = {
        #if DEBUG
        return [${list(development)}]
        #else
        return []
        #endif
    }()
    /// The Firefox add-on id.
    static let firefox = "${gecko}"

    /// What the host passes as \`caller\`: \`chrome-extension://<id>/\` for Chromium browsers, the add-on id for Firefox.
    static let callers: Set<String> = Set((chromium + development).map { "chrome-extension://\\($0)/" } + [firefox])
}
`;
const target = join(root, 'App/Core/Relay/ExtensionIDs.swift');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch {}
  if (current !== text) { console.error('App/Core/Relay/ExtensionIDs.swift is out of date: run node scripts/generate-extension-ids.mjs'); process.exit(1); }
  console.log('ok: ExtensionIDs.swift is current');
} else {
  writeFileSync(target, text);
}
